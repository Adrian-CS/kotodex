/** Idioma del sistema si está entre los que hay; si no, inglés. */
export function idiomaDelSistema(): Idioma {
  for (const etiqueta of navigator.languages ?? [navigator.language]) {
    const base = etiqueta.toLowerCase().split("-")[0];
    if (base === "es" || base === "en" || base === "ja") return base;
  }
  return "en";
}

