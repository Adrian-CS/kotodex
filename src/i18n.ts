const TEXTOS: Record<Idioma, Record<Claves, string>> = { es, en, ja };

export type T = (clave: Claves, params?: Record<string, string | number>) => string;

/** Devuelve la función de traducción del idioma dado. `{x}` se sustituye por params.x */
export function crearT(idioma: Idioma): T {
  const tabla = TEXTOS[idioma] ?? TEXTOS.en;
  return (clave, params) => {
    const texto = tabla[clave] ?? es[clave] ?? clave;
    if (!params) return texto;
    return texto.replace(/\{(\w+)\}/g, (_, nombre) => String(params[nombre] ?? `{${nombre}}`));
  };
}

