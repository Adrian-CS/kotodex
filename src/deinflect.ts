interface Rule { from: string; to: string; in: number; out: number }

const mask = (s: string) => [...s].reduce((m, c) => m | CODES[c], 0);

const RULES: [string, Rule[]][] = TABLE.map(([reason, rows]) => [
  reason,
  rows.map(row => {
    const [from, to, rIn, rOut] = row.split(":");
    return { from, to, in: mask(rIn), out: mask(rOut) };
  }),
]);

export interface Deinflection {
  /** Forma candidata, ya sin la conjugación. */
  term: string;
  /** Clases posibles (V1, V5…); 0 = la palabra tal cual, sin restricción. */
  rules: number;
  /** Conjugaciones deshechas, de la forma de diccionario hacia fuera: ["causativa pasiva", "pasado"]. */
  reasons: string[];
}

/** Tope de candidatos: sin él, palabras largas con muchas reglas encadenadas se disparan. */
const MAX_CANDIDATES = 200;

/**
 * Todas las formas de diccionario que podrían haber producido `source`, incluida `source` misma
 * (la primera, con reasons vacío). No comprueba si existen: eso lo hace la búsqueda.
 */
export function deinflect(source: string): Deinflection[] {
  const results: Deinflection[] = [{ term: source, rules: 0, reasons: [] }];
  const seen = new Set<string>([`${source}\u00000`]);

  for (let i = 0; i < results.length && results.length < MAX_CANDIDATES; i++) {
    const { term, rules, reasons } = results[i];
    for (const [reason, ruleList] of RULES) {
      for (const rule of ruleList) {
        if (rules !== 0 && (rules & rule.in) === 0) continue;
        if (!term.endsWith(rule.from)) continue;
        const length = term.length - rule.from.length + rule.to.length;
        if (length <= 0) continue;
        const next = term.slice(0, term.length - rule.from.length) + rule.to;
        const key = `${next}\u0000${rule.out}`;
        if (seen.has(key)) continue;
        seen.add(key);
        results.push({ term: next, rules: rule.out, reasons: [reason, ...reasons] });
      }
    }
  }
  return results;
}

/**
 * 勉強する → 勉強. JMdict no guarda estos verbos con la する: la entrada es el sustantivo con
 * rules "vs". Devuelve null si no acaba en する.
 */
export function suruStem(term: string): string | null {
  for (const suffix of ["する", "為る"]) {
    if (term.length > suffix.length && term.endsWith(suffix)) return term.slice(0, -suffix.length);
  }
  return null;
}

/** ¿Encaja un candidato con una entrada del diccionario? Sin "rules" en el diccionario, se acepta. */
export const matchesRules = (candidate: number, entry: number) =>
  candidate === 0 || entry === 0 || (candidate & entry) !== 0;
