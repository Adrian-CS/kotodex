// Deshace conjugaciones para poder buscar 食べた, 読まなかった o 高くない.
// La tabla está portada del deinflector de Yomitan (ext/data/deinflect.json), con los nombres
// de las razones en español; el algoritmo es el mismo: quitar sufijos hacia atrás hasta llegar
// a algo que esté en el diccionario.
//
// Cada regla anota la clase de palabra que debe tener la forma de entrada y la que tendrá el
// resultado. Esas clases son las del campo "rules" de term_bank, así que la búsqueda puede
// descartar candidatos imposibles: した da しる como pasado de un 一段, pero 知る es 五段 y se cae.

export const V1 = 1 << 0;     // 一段: 食べる
export const V5 = 1 << 1;     // 五段: 読む
export const VS = 1 << 2;     // する
export const VK = 1 << 3;     // 来る
export const VZ = 1 << 4;     // ずる: 信ずる
export const ADJ_I = 1 << 5;  // adjetivo en -い
const IRU = 1 << 6;           // forma intermedia (…ている) que se conjuga como 一段

/** Códigos de la tabla de abajo. */
const CODES: Record<string, number> = { "1": V1, "5": V5, s: VS, k: VK, z: VZ, a: ADJ_I, i: IRU };

/** Clases tal y como las escribe term_bank: "v5 vt" → V5. Lo desconocido se ignora. */
const TERM_RULES: Record<string, number> = { v1: V1, v5: V5, vs: VS, vk: VK, vz: VZ, "adj-i": ADJ_I };
export const rulesMask = (rules: string): number =>
  rules.split(" ").reduce((m, r) => m | (TERM_RULES[r] ?? 0), 0);

